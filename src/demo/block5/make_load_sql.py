#!/usr/bin/env python3
"""
make_load_sql.py  -- regenerate tsql/01_load_docs.sql from docs/*.md.

The entirely-in-T-SQL example needs the runbook text inside SQL Server. Rather
than mount files into the container (and fight UTF-8/BULK quirks), we emit plain
INSERT statements with the doc text as N'...' literals. Re-run this if you edit
the docs. Standard library only.
"""
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = sorted(glob.glob(os.path.join(HERE, "docs", "*.md")))
OUT = os.path.join(HERE, "tsql", "01_load_docs.sql")


def esc(s):
    return s.replace("'", "''")


def main():
    lines = [
        "/* GENERATED by make_load_sql.py from docs/*.md -- do not edit by hand. */",
        "USE DbaDocs;",
        "GO",
        "DELETE FROM dbo.KbDoc;",
        "GO",
    ]
    for path in DOCS:
        name = os.path.basename(path)
        with open(path, encoding="utf-8") as fh:
            content = fh.read()
        lines.append(
            f"INSERT INTO dbo.KbDoc (DocName, Content) VALUES (N'{esc(name)}', N'{esc(content)}');"
        )
    lines += ["GO", "SELECT DocName, LEN(Content) AS chars FROM dbo.KbDoc ORDER BY DocId;", "GO"]

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {OUT} ({len(DOCS)} docs)")


if __name__ == "__main__":
    main()
